/* 세 번째 인자 <b>age</b> 는 나이대 열쇠(2030·4050·60)다 — <b>안 주면 안 붙는다.</b>
   모르는 것을 기본값으로 채우면 화면이 그것을 사실로 적는다 (1번). */
function stageScript(stage,src,age){
  var k=String(stage==null?'':stage),A=ageOf(age),out;
  /* 아직 한 번도 못 건 분과 통화가 된 분 — 둘 다 <b>첫 마디</b>가 필요하다.
     그 첫 마디는 어디서 오신 분인가로 갈리므로 taSay 가 답한다. */
  if(k==='TA'||k==='미접촉'){
    var S=taSay(src);
    out={t:S.t,say:S.say,next:'',avoid:'',stop:'',tip:S.tip,src:true};
  }
  else out=SAY[k]?{t:SAY[k].t,say:SAY[k].say,next:SAY[k].next,
                   avoid:SAY[k].avoid,stop:SAY[k].stop,tip:SAY[k].tip,src:false}:null;
  if(!out)return null;
  /* 나이대 한마디는 <b>말 끝에 붙입니다</b> — 앞에 끼워 넣으면
     용건보다 먼저 나오게 됩니다. 알 수 없으면 <b>아무것도 안 붙입니다</b>. */
  out.age=A?{k:A.k,t:A.t,chip:A.chip,tip:A.tip,no:A.no}:null;
  if(A&&A.add)out.say=out.say+'\n'+A.add;
  return out;
}
function taSay(src){
  var v=String(src==null?'':src),i;
  for(i=0;i<TA_SRC.length;i++)if(TA_SRC[i].re.test(v))return TA_SRC[i];
  return TA_ANY;
}

