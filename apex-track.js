/* ══ 🎬 발표 덱 트랙 — 이름·언제 쓰나·차례를 아는 곳은 <b>여기 하나</b> ══════

   사장님 말씀 (2026-11-05) 「우선 재무설계 계산기에서 <b>발표덱이 바로
   보이게</b> 하라니까 안되고 있어」 · 「오늘 에서 <b>AP, PC 에서 각자 뜰 수
   있도록 각 파트별로</b> 다 넣어줘」.

   그러려면 「오늘」(app/index.html)도 트랙 이름을 알아야 합니다. 여태 그 표는
   계산기(app/finance.html) 안에만 있었습니다.

   ★★ <b>본체에 또 적지 않습니다.</b> 판 X224 에서 이 표가 두 벌이 되어
     <b>쿠폰 트랙이 두 번 조용히 사라졌습니다</b>. 그래서 아예 파일을 따로
     떼어, 계산기와 본체가 <b>같은 한 표</b>를 봅니다 (CLAUDE.md 5번).
   ★ 단계표(apex-stage.js)에 넣지 않은 까닭 — 그 파일은 246KB 이고 전역
     이름을 여럿 세웁니다. 계산기 틀에 그것을 통째로 실으면 느려지고
     이름이 부딪힙니다. 이 표는 <b>다섯 줄</b>이라 따로 두는 것이 쌉니다.
   ★ 트랙을 하나 더 만들 때는 <b>여기만</b> 고칩니다. 차례(order)에 안 적은
     트랙은 <b>뒤에 저절로 붙습니다</b> — 빠뜨릴 자리가 없습니다.
   ⚠ 덱 주소를 만드는 자리는 <b>계산기 한 곳</b>(apexDeckUrl)입니다. 여기
     주소를 적지 마십시오 — 본체는 트랙 이름만 넘깁니다.
   ⚠ 금액·기간·한도 숫자를 여기 적지 마십시오 (CLAUDE.md 2번).           */
(function(){
  var T = {
    /* 고르개·단추에 찍히는 이름 */
    name:{ w:'₩ 연금', d:'$ 달러', t:'📈 투자·세금', e:'🎓 교육자금',
           c:'🏢 일시납·쿠폰 vs 부동산' },
    /* <b>언제 꺼내나</b> — 고객이 그 말을 하실 때 */
    when:{ w:'노후 생활비가 걱정이라고 하실 때',
           d:'환율·비과세·달러 자산 이야기가 나올 때',
           t:'투자 수익률과 세금을 같이 볼 때',
           e:'자녀 교육비·유학 이야기가 나올 때',
           c:'"차라리 상가 하나 사지" 라고 하실 때 · 목돈을 한 번에 넣고 매달 받는 이야기' },
    /* 보여 주는 차례만 정합니다 — 여기 없는 트랙은 뒤에 붙습니다 */
    order:['w','d','t','e','c']
  };
  /* 차례대로 돌려주는 자 — 부르는 쪽이 또 정렬하지 않습니다 (5번) */
  T.keys = function(){
    var k = Object.keys(T.name), 차 = T.order;
    return k.sort(function(a,b){
      var i=차.indexOf(a), j=차.indexOf(b);
      if(i<0)i=차.length; if(j<0)j=차.length;
      return i-j;
    });
  };
  window.APEX_TRACK = T;
})();
