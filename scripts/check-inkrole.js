/* ══════════════════════════════════════════════════════════════════
   check-inkrole.js — <b>선 색을 글자색으로 쓰지 않나.</b>

   사장님 말씀 (2026-10-05) — 남은 스물다섯 화면이 <b>연한 바탕 위 호박·초록
   글</b>과 <b>흐린 회색</b>에 막혀 있다고 여쭈었고, 사장님이 <b>ⓒ</b> 로
   답하셨습니다 — 「새 짙은 토큰을 만든다. 목업 결은 지키면서 대비는 6 이상」.

   ── 무엇을 보다가 이 자를 세웠나 ──────────────────────────────────
   그 흐린 회색을 쫓아가 보니 <b>#D7DCE2</b> 였고, 그것은 우리 색표의
   <b>--t-line-3</b> — <b>선(線) 토큰</b>입니다. 「끄기 상태 · 체크칸 테두리 ·
   스크롤바」 라고 적혀 있습니다. 그 색을 <b>글자색</b>으로 쓰면 흰 바탕 위
   <b>1.38:1</b> — 흰 종이에 흰 글씨에 가깝습니다.

   ★ <b>제가 만든 탈이 아닙니다.</b> --ink-6 은 다리를 놓기 전에도
     <b>#D1D5DB(1.47)</b> 였습니다(f982f62). 다리를 놓으며 1.38 이 됐습니다 —
     거의 그대로입니다. <b>처음부터 그랬다</b>는 뜻이고, 그래서 이 자는
     「고쳐라」 가 아니라 <b>「늘리지 말라」</b> 로 겁니다(check-onepal 과
     같은 방식 · 0-1번).

   ── ★ 딱 하나는 고쳤습니다 — 「모름」 ─────────────────────────────
   열일곱 자리 중 셋이 <b>「모름(null)」 을 적는 자리</b>였습니다 —
   txNum · coNum · ctNum 의 「—」. CLAUDE.md <b>1번</b>이 「모름(null)과 0을
   구분한다. 못 읽은 것을 0으로 적으면 「보장이 없다」 는 뜻이 되어 버린다」
   고 적어 두었는데, <b>안 보이는 「—」 는 「아무것도 없다」 로 읽힙니다.</b>
   규칙을 적어 두고 화면에서는 안 지키고 있었습니다.
   → <b>osNoVal() 한 곳</b>으로 모으고 --t-sub(4.62)로 올렸습니다.

   ── 보는 것 (넓게 잡지 않습니다 · 8번) ────────────────────────────
     [1] 선 토큰을 <b>글자색</b>으로 쓰는 자리가 <b>늘지 않았나</b> (기준선)
     [2] 「모름」 을 적는 글이 <b>한 곳</b>인가 — osNoVal (5번)
     [3] 그 한 곳이 <b>선 토큰을 안 쓰는가</b> — 읽히는 글자 토큰인가
     [4] 셋이 다 osNoVal 을 <b>부르는가</b> — 하나라도 제가 적으면 두 벌
     [5] 밑줄 색·바탕·스크롤바로 쓰는 것은 <b>건드리지 않는다</b> — 선이
         맞는 자리라서 그렇습니다. <b>헛것을 잡지 않습니다</b> (8번)

   ⚠ <b>쪽지를 세지 않습니다.</b> 이 파일과 index.html 의 주석에 「선 토큰을
     글자색으로」 같은 말이 적혀 있어, 날글을 세면 제 쪽지가 알리바이가
     됩니다. 주석을 <b>걷어내고</b> 셉니다.                                */
const fs = require('fs');
let bad = 0;
const is = (ok, m) => { console.log((ok ? '  ✓ ' : '  ✗ ') + m); if (!ok) bad++; };

const RAW = fs.readFileSync('app/index.html', 'utf8');
const CSS = fs.readFileSync('app/ui.css', 'utf8');
/* 주석과 APP_BUILD_NOTE 를 걷어냅니다 — 제 쪽지가 알리바이가 되지 않게 */
const SRC = RAW.replace(/<!--[\s\S]*?-->/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ')
               .replace(/^var APP_BUILD_NOTE=.*$/m, ' ');

/* ── 선(線) 토큰 — ui.css 가 「선」 이라고 적어 둔 이름들 ──────────────
   값이 아니라 <b>이름</b>으로 셉니다. 값을 적으면 색을 바꿀 때 이 자가
   거짓이 됩니다 (5번).                                                 */
const 선토큰 = ['--t-line', '--t-line-2', '--t-line-3', '--t-line-b'];
/* --ink-6 · --ink-7 · --ink-8 은 그 선 토큰을 <b>가리키는 옛 이름</b>입니다 */
const 선별칭 = [];
선토큰.forEach(t => {
  const rx = new RegExp('(--ink-\\d)\\s*:\\s*var\\(' + t + '\\)', 'g');
  let m; while ((m = rx.exec(RAW))) if (선별칭.indexOf(m[1]) < 0) 선별칭.push(m[1]);
});
const 선전부 = 선토큰.concat(선별칭);

console.log('[0] <b>선 토큰</b>이 무엇인지 — 이름으로 찾습니다');
is(선별칭.length > 0, '  선 토큰을 가리키는 옛 이름을 <b>찾았다</b> — ' +
   (선별칭.join(' · ') || '없음') + ' (0개면 이 자가 아무것도 못 보는 것입니다 · 8번)');

console.log('\n[1] ★ <b>선 색을 글자색으로</b> 쓰는 자리가 늘지 않았나');
/* ⚠ text-decoration-color · background-color · scrollbar-color 는 <b>뺍니다</b> —
   선이 맞는 자리입니다. (?<![-\w]) 가 그 일을 합니다. */
const 글자로 = [];
선전부.forEach(t => {
  const rx = new RegExp('(?<![-\\w])color\\s*:\\s*var\\(' + t + '[^)]*\\)', 'g');
  const n = (SRC.match(rx) || []).length + (CSS.match(rx) || []).length;
  if (n) 글자로.push(t + ' ' + n + '곳');
});
const 합 = 글자로.reduce((a, x) => a + parseInt(x.match(/(\d+)곳/)[1], 10), 0);
const BASE = { 글자로쓴선: 14 };
/* ⚠ 14 는 <b>재서 적은 수</b>입니다 (2026-10-05). 처음에 17이었고 「모름」
   셋을 osNoVal 로 올려 14가 되었습니다. 줄이면 같이 내리고, <b>늘면
   빨간불</b>입니다 — check-onepal · check-skinmap 과 같은 방식 (0-1번).
   ★ 남은 열넷은 <b>「흐리게 둔 뜻」 을 지울지</b> 라서 사장님이 정하실
     일입니다. 제가 혼자 올리지 않습니다 (1번).                        */
is(합 <= BASE.글자로쓴선,
   '  선 토큰을 글자색으로 쓰는 자리 <b>' + 합 + '곳</b> — 기준선 ' + BASE.글자로쓴선 +
   (합 ? ' · ' + 글자로.join(' / ') : '') +
   (합 < BASE.글자로쓴선 ? ' ← 기준선을 ' + 합 + ' 로 내려 주십시오' : '') +
   (합 > BASE.글자로쓴선 ? ' ← ★ <b>늘었습니다.</b> 선 색은 흰 바탕 위 1.38:1 입니다 — 글자가 안 보입니다' : ''));

console.log('\n[2] ★★ 「<b>모름</b>」 을 적는 글이 <b>한 곳</b>인가 (5번)');
is(/function\s+osNoVal\s*\(/.test(SRC),
   '  「모름」 을 적는 함수 <b>osNoVal</b> 이 있다');
/* ⚠★ <b>처음에 제 자가 헛것을 잡았습니다.</b> osNoVal <b>자신</b>이 그 글을
   들고 있으니 「손으로 적는 자리 1곳」 이라고 울렸습니다. 한 곳에 모으라고
   시켜 두고, 모아 둔 그 한 곳을 잘못이라고 한 것입니다.
   → <b>osNoVal 의 몸을 먼저 걷어내고</b> 셉니다. 「헛것을 잡는 점검은 안 잡는
     점검보다 나쁘다」(8번) — 사람이 자를 안 믿게 됩니다.                */
const 모름집 = (SRC.match(/function\s+osNoVal\s*\([^)]*\)\s*\{[^}]*\}/) || [''])[0];
const 밖에서 = 모름집 ? SRC.replace(모름집, ' ') : SRC;
const 날글모름 = (밖에서.match(/<span style="color:var\(--[a-z0-9-]+\)">—<\/span>/g) || []);
is(날글모름.length === 0,
   '  ★ 「모름」 을 <b>제 손으로 적는 자리가 없다</b> — ' + 날글모름.length +
   '곳 (osNoVal 자신은 뺀 수입니다)' +
   (날글모름.length ? ' ← ' + 날글모름.join(' · ') + ' 를 osNoVal() 로 바꾸십시오' : ''));

console.log('\n[3] ★ 그 한 곳이 <b>읽히는 글자 토큰</b>을 쓰는가');
const 몸 = (SRC.match(/function\s+osNoVal\s*\([^)]*\)\s*\{[^}]*\}/) || [''])[0];
is(!!몸, '  osNoVal 의 몸을 <b>찾았다</b> — ' + (몸 ? 몸.length + '자' : '못 찾았습니다'));
const 선을씀 = 선전부.some(t => 몸.indexOf('var(' + t) >= 0);
is(!!몸 && !선을씀,
   '  ★★ osNoVal 이 <b>선 토큰을 안 쓴다</b>' + (선을씀 ? ' ← 선 색은 1.38:1 로 「모름」 이 안 보입니다 (1번)' : ''));
is(!!몸 && /var\(--t-(sub|ink)/.test(몸),
   '  ★ 글자 토큰(--t-sub · --t-ink 계열)을 쓴다 — ' +
   ((몸.match(/var\((--t-[a-z0-9-]+)\)/) || [])[1] || '없음'));

console.log('\n[4] ★ 셋이 <b>다 그 한 곳을 부르는가</b> — 하나만 빠져도 두 벌 (5번)');
['txNum', 'coNum', 'ctNum'].forEach(fn => {
  const f = (SRC.match(new RegExp('function\\s+' + fn + '\\s*\\([^)]*\\)\\s*\\{[^}]*\\}')) || [''])[0];
  is(!!f && /osNoVal\s*\(\s*\)/.test(f),
     '  ' + fn + ' 이 <b>osNoVal()</b> 을 부른다' + (f ? '' : ' ← 함수를 못 찾았습니다'));
});

console.log('\n[5] ⚠ <b>선이 맞는 자리는 안 건드렸나</b> — 헛것을 잡지 않습니다 (8번)');
const 밑줄 = (SRC.match(/text-decoration-color\s*:\s*var\(--ink-6/g) || []).length;
const 바탕 = (SRC.match(/background[^:]*:\s*var\(--ink-6/g) || []).length +
             (SRC.match(/scrollbar-color\s*:\s*var\(--ink-6/g) || []).length;
is(밑줄 + 바탕 > 0,
   '  밑줄 색 ' + 밑줄 + '곳 · 바탕·스크롤바 ' + 바탕 + '곳은 <b>그대로 있다</b>' +
   ' — 선 색이 맞는 자리입니다 (0곳이면 이 자가 잘못 지운 것입니다)');

console.log('\n[6] ★ <b>--t-neg-d</b> 가 색표에 한 번만 있는가 (사장님 ⓒ)');
const neg = (CSS.match(/--t-neg-d\s*:/g) || []).length;
is(neg === 1, '  --t-neg-d 가 <b>ui.css 에 한 번</b> 적혀 있다 — ' + neg + '번');
is((SRC.match(/--t-neg-d\s*:/g) || []).length === 0,
   '  ★ index.html 에 <b>또 안 적었다</b> — 색표는 한 벌입니다 (5번)');
const negVal = ((CSS.match(/--t-neg-d\s*:\s*(#[0-9A-Fa-f]{6})/) || [])[1] || '').toUpperCase();
is(negVal === '#B91C1C',
   '  ★ 값이 <b>앱이 가장 많이 쓰던 그 색</b>이다 — ' + (negVal || '없음') +
   ' (제가 고른 색이 아니라 84번 쓰이던 색입니다 · 1번)');

console.log('\n──────────────────────────────');
console.log(bad ? ('✗ ' + bad + '가지 빨간불')
  : '✓ 선 색은 선 자리에만 · 「모름」 은 한 곳에서 읽히게 적습니다.');
process.exit(bad ? 1 : 0);
