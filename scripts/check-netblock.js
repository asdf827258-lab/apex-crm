/* ══════════════════════════════════════════════════════════════════
   check-netblock.js — <b>점검이 사장님의 진짜 서버를 읽지 않는가.</b>

   ── 왜 이 자를 세웠나 (2026-09-30) ───────────────────────────────
   「같은 코드인데 <b>로컬은 초록 · CI 는 빨간불</b>」 이 <b>세 번</b>
   있었습니다. 세 번째를 파 보니 뿌리가 이것이었습니다 —

     check-hmexact 에 <b>바깥을 막는 줄이 없었습니다.</b> 그래서 CI 에서는
     <b>진짜 Supabase 가 답했습니다</b> — 사장님의 진짜 공지 일곱 칸과
     <b>11.9MB 사진</b>까지 그려져 잎이 116개였습니다. 제 컨테이너는 그
     서버에 못 닿아 34개였습니다.
     <b>색이 아니라 자료가 달랐습니다.</b>

   즉 <b>자가 밖을 보면 그날 그곳의 서버 상태를 재게 됩니다.</b>
   점검은 「코드가 맞나」 를 물어야 하는데 「지금 서버에 무엇이 있나」 를
   묻고 있었던 것입니다.

   ── 막아야 하는 까닭 셋 ──────────────────────────────────────────
     ① <b>같은 코드는 어디서 돌려도 같은 답</b>이라야 자가 자입니다 (8번)
     ② 사장님 자료를 읽으면 <b>그 글이 CI 기록에 그대로 찍힙니다.</b>
        공지에 고객 이름이 있으면 남습니다 (3번)
     ③ PR 마다 진짜 서버를 부릅니다 — 무료 한도를 세 배 넘긴 적이
        있습니다 (7번)

   ── 보는 것 ───────────────────────────────────────────────────────
     [1] ★ <b>홈 색을 재는 자(check-hmexact)</b>는 반드시 막는다
         — 실제로 여기서 물렸습니다
     [2] 브라우저를 쓰면서 <b>안 막는 자</b>가 늘지 않는다 (눈금)

   ── ⚠ <b>0 을 요구하지 않습니다</b> ───────────────────────────────
   밖을 <b>봐야 하는</b> 자도 있습니다 — 진짜 기사 주소가 살아 있나 같은
   것입니다. 전부 막으라고 하면 그런 자가 거짓으로 빨개집니다.
   「헛것을 잡는 점검은 안 잡는 점검보다 나쁘다」 (8번).
   그래서 <b>수를 세고 늘지만 못하게</b> 합니다 — 줄이면 기준선도 같이
   내립니다. 목각 옷 눈금(check-skinmap)과 같은 방식입니다 (0-1).
   ══════════════════════════════════════════════════════════════════ */
const fs = require('fs'), path = require('path');
const ROOT = process.cwd(), DIR = path.join(ROOT, 'scripts');
let bad = 0;
const is = (ok, m) => { console.log((ok ? '  ✓ ' : '  ✗ ') + m); if (!ok) bad++; };

/* ★ <b>2026-09-30 에 잰 값</b>입니다. 막을 때마다 이 수를 같이 내리십시오 —
   안 내리면 다음 사람이 「아직 120개나 남았네」 라고 잘못 읽습니다.      */
const BASE = { 안막음: 120 };

const files = fs.readdirSync(DIR).filter(f => /^check-.*\.js$/.test(f)).sort();
const 브라우저 = [], 안막음 = [];
for (const f of files) {
  const s = fs.readFileSync(path.join(DIR, f), 'utf8');
  if (!/chromium\.launch/.test(s)) continue;
  브라우저.push(f);
  /* 막는 줄 — ctx.route / page.route 로 127.0.0.1 밖을 abort 하는 것 */
  if (!/\.route\('\*\*:\/\/\*\*'/.test(s)) 안막음.push(f);
}

console.log('\n[1] ★ <b>홈 색을 재는 자</b>는 바깥을 막는다 — 여기서 물렸습니다');
const HM = fs.readFileSync(path.join(DIR, 'check-hmexact.js'), 'utf8');
is(/\.route\('\*\*:\/\/\*\*'/.test(HM),
   '  check-hmexact 가 <b>바깥을 막는다</b> — 안 막으면 CI 에서 진짜 공지가 그려집니다');
is(/abort\(\)/.test(HM), '  막은 것을 <b>끊는다</b>(abort) — 기다리게 두면 곳마다 다른 순간을 잽니다');

console.log('\n[2] 바깥을 <b>안 막는 자</b>가 늘지 않았다 (눈금)');
console.log('     브라우저를 쓰는 자 ' + 브라우저.length + '개 · 그중 안 막는 자 <b>' + 안막음.length + '</b>개');
is(안막음.length <= BASE.안막음,
   '  안 막는 자가 <b>' + 안막음.length + '개</b> — 기준선 ' + BASE.안막음 + ' 이하' +
   (안막음.length > BASE.안막음 ? (' ← 늘었습니다: ' + 안막음.slice(-3).join(' · ')) : ''));
/* ⚠ 여기에 「늘 초록인 줄」 을 두지 않습니다 — 안 울리는 알람은 알람이
   아닙니다 (8번). 줄었을 때 할 말은 아래에서 <b>그냥 적습니다</b>.    */
if (안막음.length < BASE.안막음)
  console.log('     ★ ' + (BASE.안막음 - 안막음.length) + '개를 줄이셨습니다 — BASE 를 ' +
              안막음.length + ' 로 내려 주십시오');

console.log('\n──────────────────────────────');
console.log(bad ? ('✗ ' + bad + '가지 빨간불')
                : '✓ 홈 색을 재는 자는 바깥을 막고, 안 막는 자는 늘지 않았습니다.');
process.exit(bad ? 1 : 0);
