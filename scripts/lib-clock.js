/* ══════════════════════════════════════════════════════════════════
   lib-clock.js — <b>시계를 못 박는 자리. 한 곳입니다.</b>

   사장님 말씀 (2026-10-09) — 「홈 높이 자에 <b>시계 못 박는</b> 다음판 해줘」.

   ── 왜 ────────────────────────────────────────────────────────────
   홈은 <b>때에 따라 길이가 다릅니다.</b> 아침·낮·저녁으로 카드가 갈리고,
   같은 칸도 글이 달라 접히는 줄 수가 바뀝니다. 그런데 홈 높이를 재는 자
   넷이 <b>시계를 안 봤습니다</b> — 그냥 「지금」 을 쟀습니다. 그래서 —
     · CI 가 14~15시(UTC)에 돌면 <b>초록</b>
     · 17시에 돌면 <b>빨간불</b>
   이고, #548·#549·#550 <b>세 판이 그 틈으로 들어갔습니다.</b> 사장님이
   「4.2화면이 끝」 이라고 못 박으신 선을 아침·저녁에 넘고 있었는데도
   아무도 안 울렸습니다 (2026-10-09 · 판 X77 에서 재어 알았습니다).

   ── 무엇을 하나 ───────────────────────────────────────────────────
   브라우저의 <b>시계를 못 박습니다</b>. 날짜까지 고정이라, 언제 돌려도
   같은 수가 나옵니다. 「지금 몇 시냐」 를 <b>묻지 않습니다</b> — 묻는
   순간 CI 가 도는 시각에 다시 매입니다.

   ── 지킨 것 ───────────────────────────────────────────────────────
   ★ <b>여기 한 곳</b>입니다 (5번). 네 자가 이것을 부르고, 저마다 Date 를
     손으로 바꾸지 않습니다 — 베끼면 넷 중 하나만 늙습니다.
   ★ <b>흐르는 시계</b>입니다. now 를 한 수로 굳히지 않고 못 박은 자리에서
     <b>같이 흐르게</b> 둡니다 — 굳히면 「몇 초 지났나」 를 세는 자리가
     영원히 0 이 되어 기다림이 안 끝납니다.
   ★ <b>되돌릴 일이 없습니다</b> — 못 박은 창(context)은 그 자리에서 쓰고
     닫습니다. 한 창 안에서 바꿨다 되돌리는 자(check-crmask)와 다릅니다.
   ★ 창의 시간대를 <b>UTC</b> 로 둡니다. 안 그러면 못 박은 절대 시각과
     「getHours」 가 어긋나, 「저녁」 이라고 적고 아침을 잽니다.
   ══════════════════════════════════════════════════════════════════ */

/* 못 박는 <b>날</b> — 아무 날이나 쓰지 않습니다. 평일(금요일)이고 달
   가운데라, 주말·월말 때문에 홈이 달라지는 자리에 안 걸립니다.        */
const DAY = { y: 2026, m: 10, d: 9 };

/* <b>세 때</b> — 앱이 하루를 가르는 그 자리와 같은 세 토막입니다
   (osBriefKind: 11시 전 아침 · 17시 전 낮 · 그 뒤 저녁).              */
const WHEN = [
  { k: '아침', h: 8,  왜: '미션이 다 남아 있고 알람도 다 남은 때' },
  { k: '낮',   h: 14, 왜: '여태 CI 가 돌던 때 — 옛 눈금이 이 때의 것입니다' },
  { k: '저녁', h: 20, 왜: '알람이 다 지나고 저녁 칸이 서는 때' }
];

/* 창의 시간대 — 이 때 「getHours」 가 아래 h 와 같습니다 */
const TZ = 'UTC';

/* 그 때의 <b>절대 시각</b> — 지금 시각을 묻지 않고 날짜로 짓습니다 */
function msOf(h) { return Date.UTC(DAY.y, DAY.m - 1, DAY.d, h, 30, 0); }

/* 창을 만들 때 넘기는 것 — 시간대를 빠뜨리지 못하게 여기서 들고 있습니다 */
function ctxOpt(extra) {
  const o = Object.assign({ viewport: { width: 390, height: 844 } }, extra || {});
  o.timezoneId = TZ;
  return o;
}

/* ★ <b>창이 열리기 전에</b> 박습니다. 화면이 그려지는 동안 시각을 보는
   자리가 있어(osBriefKind · almLeftToday) 나중에 박으면 늦습니다.
   ★ <b>박는 방법은 이 한 줄뿐</b>입니다 (5번). 때(h)로 부르는 쪽과 날짜
     글자(iso)로 부르는 쪽이 있는데, 둘 다 여기를 지납니다 —
     check-phonefit 은 적어 둔 눈금이 <b>2026-09-15 09:00Z</b> 에서 잰
     것이라 그 날을 지켜야 하고, 그렇다고 박는 코드가 두 벌이면 한쪽만
     늙습니다. 그래서 <b>날짜만 다르고 방법은 하나</b>입니다.           */
async function pinAt(ctx, ms) {
  await ctx.addInitScript((at) => {
    const RD = Date, t0 = RD.now();
    const 지금 = () => at + (RD.now() - t0);        /* 못 박은 자리에서 흐른다 */
    const D = function (...a) { return a.length ? new RD(...a) : new RD(지금()); };
    D.now = () => 지금();
    D.parse = RD.parse; D.UTC = RD.UTC; D.prototype = RD.prototype;
    window.Date = D;
  }, ms);
  return ms;
}
/* 때(아침·낮·저녁)로 박는다 — 못 박은 날의 그 시각 */
async function pin(ctx, h) { return pinAt(ctx, msOf(h)); }
/* 날짜 글자로 박는다 — 옛 눈금이 매여 있는 날을 지킬 때 */
async function pinIso(ctx, iso) { return pinAt(ctx, new Date(iso).getTime()); }

/* ★ <b>Node 쪽에서도 같은 시계를 본다.</b>
   자가 Node 에서 「오늘」 을 제 손으로 또 셈하면 창의 시계와 <b>하루가
   갈립니다</b> — 창은 못 박은 날이고 Node 는 CI 가 도는 진짜 날입니다.
   판 X83 에서 <b>check-day·check-team</b> 이 그래서 헛 빨간불을 켰습니다 :
     · 「1주 뒤」 가 그 날짜로 들어간다      ← 하루 어긋남
     · 걸린 시각이 진짜 그 순간이다          ← 38,389초 어긋남
     · 오늘 몫으로 들어간다 — 하루 한 줄    ← fb_date 가 하루 어긋남
   check-clients 가 2026-10-05 에 같은 자리에서 배운 것과 같습니다 —
   「자가 날짜를 제 손으로 만들면 앱과 어긋날 수 있습니다」.
     · kstDay(h)     → 그 때의 <b>한국 날짜</b> 글자 (앱이 그렇게 적습니다)
     · kstDay(h, 7)  → 이레 뒤
   ★ <b>창이 아는 지금</b>(ms)이 필요하면 msOf(h) 를 쓰거나, 더 좋게는
     그 창에 직접 물으십시오 — 여기서 또 셈하지 마십시오.              */
function kstDay(h, plus) {
  return new Date(msOf(h) + 9 * 3600000 + (plus || 0) * 86400000)
    .toISOString().slice(0, 10);
}

/* 그 때를 사람이 읽는 글로 — 적을 때 손으로 또 쓰지 않게 */
function label(w) { return w.k + '(' + w.h + '시)'; }

module.exports = { DAY, WHEN, TZ, msOf, ctxOpt, pinAt, pin, pinIso, kstDay, label };
