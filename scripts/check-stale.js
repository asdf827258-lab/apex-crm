/* ══════════════════════════════════════════════════════════════════
   check-stale.js — <b>「아직 못 한다」 고 적으려면 못 하는 것이 사실이어야 한다.</b>

   ── 왜 이 자를 세웠나 — <b>세 판 내리 같은 일을 겪었습니다</b> ────────
   말씀대장(docs/말씀대장.tsv)과 그것을 읽어 주는 scripts/audit.js 는
   <b>세션을 열 때 제일 먼저</b> 읽는 지도입니다. 그 지도가 낡으면
   <b>모든 세션이 거짓 지도로 출발합니다.</b> 실제로 이렇게 겪었습니다 —

     · <b>X02</b> (2026-10-05) — 「연한 바탕 위 호박·초록 글은 목업에 짙은
       단이 <b>없어</b> 대비가 떨어진다」 고 적혀 있었습니다. <b>있었습니다</b>
       (--t-warn-d · --t-pos-d). 그 거짓 전제로 사장님께 「읽기가 나빠집니다」
       라고 여쭈어 <b>한 판을 버렸습니다.</b>
     · <b>X41</b> (2026-10-06) — 「위 칩 둘(알람 N개 · 연속 N일) <b>둘 다
       못 셈</b>」 이라 적혀 있었습니다. <b>둘 다 셉니다</b> —
       almLeftToday() · actStreak() 이 있고 화면에 data-ask 까지 달려 있습니다.
     · <b>H24</b> (2026-10-03) — 「push_subs 가 <b>0줄</b>」 이라 적혀
       있었는데 사장님이 그 뒤에 담으셔서 <b>2줄</b>이었습니다.

   CLAUDE.md 0-1 번이 이것을 적어 두었습니다 — 「<b>고치면 대장도 같이
   고칩니다. 코드만 고치고 대장을 안 고치면, 다음 세션은 여전히 「안 된다」고
   읽습니다.</b>」 적어 두기만 해서는 안 지켜졌습니다. <b>재게 합니다.</b>

   ── check-ledger 와 <b>반대 방향</b>입니다 ───────────────────────────
   check-ledger 는 「<b>됨</b> 이라고 적으려면 재는 자가 있어야 한다」 를 봅니다
   — 거짓 안심을 막습니다. 이 자는 그 <b>반대쪽</b>을 봅니다:
   「<b>못 한다</b> 고 적으려면 못 하는 것이 사실이어야 한다」 — <b>거짓 절망</b>을
   막습니다. 둘 다 있어야 지도가 믿을 만해집니다.

   ── 어떻게 재나 — <b>증인</b> ──────────────────────────────────────
   「못 한다」 는 말마다 <b>기계가 볼 수 있는 증인</b>을 적어 둡니다. 증인이
   <b>다 있으면</b> 그 말은 거짓입니다 — 빨간불입니다.
   ★ <b>증인을 적지 않은 말은 안 셉니다.</b> 모든 「못 한다」 를 기계가 가릴 수는
     없습니다(사장님 손이 필요한 것 · 개념이 아직 없는 것). <b>넓게 잡지 않습니다</b>
     — 헛것을 잡는 점검은 안 잡는 점검보다 나쁩니다 (8번).

   ⚠ <b>「아직 못 읽었습니다」 는 다른 말입니다.</b> 그것은 「서버에서 아직 안
     읽어 왔다」 는 뜻이고 <b>참일 수 있습니다</b>(1번 — 모르면 모른다고 합니다).
     세지 않습니다. 세는 것은 「<b>세는 자리가 없다</b>」 쪽뿐입니다.
   ══════════════════════════════════════════════════════════════════ */
const fs = require('fs');
let bad = 0;
const is = (ok, m) => { console.log((ok ? '  ✓ ' : '  ✗ ') + m); if (!ok) bad++; };

const SRC = fs.readFileSync('app/index.html', 'utf8');
const LEDGER = fs.readFileSync('docs/말씀대장.tsv', 'utf8');
const 줄 = LEDGER.split('\n').map(l => l.split('\t')).filter(r => r.length === 7);

/* ── ⚠★★ <b>글로 찾다가 세 번째로 속았습니다 — 이름표로 바꿨습니다.</b> ──
   처음에 대장 메모에서 「세는 자리가 없」 같은 <b>글귀</b>를 찾았습니다. 그러자
   X41 의 <b>역사 기록</b>("그때는 세는 자리가 없어 못 세웠습니다")을 보고
   「지금 못 한다」 로 읽었습니다 — <b>헛것</b>입니다 (8번). 역사는 지우지
   않습니다(0-1번). 자가 가려 읽어야 합니다.
   ★ 그래서 대장에 <b>⛔[아직:키] 이름표</b>를 답니다. 오늘 @toss 와
     data-ask 때도 같은 교훈이었습니다 — <b>기계가 볼 것은 기계가 읽는 자리에</b>.

   ── 증인 대장 ───────────────────────────────────────────────────
   「못 한다」 는 말마다 <b>그 말이 거짓이 되는 조건</b>을 적습니다. 증인이
   <b>다 있으면</b> 빨간불입니다 — 대장을 고치라는 뜻입니다.
   ★ 이름표를 안 단 말은 <b>안 셉니다.</b> 모든 「못 한다」 를 기계가 가릴 수는
     없습니다 — 사장님 손이 필요한 것(H24 의 「컴퓨터에서 한 번 누르시면」)은
     <b>서버 자료</b>라 원문으로 알 길이 없습니다. 넓게 잡지 않습니다 (8번).  */
const 증인 = [
  { 키: 'X02-설정',  뜻: '설정 화면을 점검 껍데기에서 못 열어 안 쟀다',
    옷입음: ['settings'] },
  /* ★★ 2026-10-06 · <b>X02-잇기 는 다 했으므로 증인을 뺐습니다</b> — org ·
     contracts(물결 6) · claims(물결 7) 셋 다 입었습니다. 대장의 이름표도 지웠습니다.
     「다 한 것」 을 「아직 못 한다」 로 두면 자가 거짓을 참으로 지킵니다 (0-1번).  */
  { 키: 'X41-칩',    뜻: '위 칩 둘(연속 N일 · 알람 N개)을 세는 자리',
    함수: ['actStreak', 'almLeftToday'] },
  { 키: 'X41-곁칸',  뜻: '곁기둥 세 칸(이번 주 · 이번 달 · 알람)을 그리는 자리',
    함수: ['hmRunSideHtml', 'hmMadiSideHtml', 'hmAlmSideHtml'] }
];
/* 옷 입은 화면 — <b>T_SKIN 한 곳</b>에게 묻습니다 (5번) */
const SKIN = (() => {
  const m = SRC.match(/var\s+T_SKIN\s*=\s*\{([^}]*)\}/);
  return m ? (m[1].match(/([A-Za-z_][A-Za-z0-9_]*)\s*:/g) || []).map(x => x.replace(/\s*:$/, '')) : [];
})();

console.log('[0] 대장을 읽었나');
is(줄.length > 50, '  말씀 ' + 줄.length + '줄 (50줄 아래면 이 자가 아무것도 못 보는 것입니다 · 8번)');

console.log('\n[1] ★★ 「<b>못 한다</b>」 고 적은 말이 <b>아직 사실인가</b>');
is(SKIN.length > 10, '  옷 입은 화면을 <b>T_SKIN 에게</b> 물었다 — ' + SKIN.length +
   '개 (10개 아래면 이 자가 아무것도 못 보는 것입니다 · 8번)');
let 재것 = 0;
증인.forEach(w => {
  const 달린줄 = 줄.filter(r => r[6].indexOf('⛔[아직:' + w.키 + ']') >= 0);
  if (!달린줄.length) {
    console.log('      · ' + w.키 + ' — 대장에 <b>이름표가 없습니다</b> (그 말이 사라졌거나 아직 안 달았습니다)');
    return;
  }
  재것++;
  const 말씀 = 달린줄.map(r => r[0]).join('·');
  const 종류 = w.함수 ? '함수' : '옷입음';
  const 다 = w.함수 || w.옷입음;
  const 있는것 = w.함수
    ? w.함수.filter(f => new RegExp('function\\s+' + f + '\\s*\\(').test(SRC))
    : w.옷입음.filter(id => SKIN.indexOf(id) >= 0);
  is(있는것.length < 다.length,
     '  ' + 말씀 + ' ⛔[' + w.키 + '] — ' + w.뜻 + ' · ' + 종류 + ' ' +
     있는것.length + '/' + 다.length + '개가 있다' +
     (있는것.length >= 다.length
       ? ' ← ★★ <b>다 있습니다. 그 말은 거짓입니다.</b> ' + 있는것.join(' · ') +
         ' — 대장 ' + 말씀 + ' 의 그 줄과 이름표를 고치십시오. ' +
         '<b>audit.js 가 세션마다 그 글을 내줍니다</b> (0-1번)'
       : ' — 아직 ' + 다.filter(f => 있는것.indexOf(f) < 0).join(' · ') + ' 가 없어 그 말이 맞습니다'));
});
is(재것 > 0, '  ★ 이름표가 달린 말 <b>' + 재것 + '개</b>를 쟀다 (0개면 이 자가 아무것도 안 잰 것입니다 · 8번)');

console.log('\n[2] ★ 「<b>아직 세는 자리가 없습니다</b>」 칸이 <b>정말 떠야 하나</b>');
/* HM_SIDE 의 칸마다 fn 이 적혀 있고, 그 함수가 있으면 그 칸은 <b>세어 그립니다</b>.
   셋 다 있으면 「못 세는 칸」(hmSideTodoHtml)은 <b>한 번도 안 뜹니다</b>.      */
const m = SRC.match(/HM_SIDE\s*=\s*\[([\s\S]*?)\];/);
is(!!m, '  HM_SIDE 표를 <b>찾았다</b>' + (m ? '' : ' ← 표 이름이 바뀌었으면 이 자도 고쳐야 합니다'));
if (m) {
  const 칸 = [];
  (m[1].match(/\{[^{}]*\}/g) || []).forEach(d => {
    const fn = (d.match(/fn\s*:\s*'([^']*)'/) || [])[1];
    const t = (d.match(/t\s*:\s*'([^']*)'/) || [])[1] || '?';
    if (fn) 칸.push({ t: t, fn: fn, 있: new RegExp('function\\s+' + fn + '\\s*\\(').test(SRC) });
  });
  is(칸.length >= 3, '  곁기둥 칸 ' + 칸.length + '개를 읽었다 — ' + 칸.map(c => c.t).join(' · '));
  const 없는것 = 칸.filter(c => !c.있);
  is(없는것.length === 0,
     '  ★ 적어 둔 fn 이 <b>다 살아 있다</b>' +
     (없는것.length ? ' ← ' + 없는것.map(c => c.t + '(' + c.fn + ')').join(' · ') +
       ' — 이름만 적고 함수가 없으면 그 칸은 <b>말없이 「못 셉니다」 로 떨어집니다</b>' : ''));
  /* ★ 셋 다 있으면 — 「못 세는 칸」 이 <b>안 뜨는 것이 사실</b>입니다.
     그 사실을 화면에도 대장에도 같이 적어야 합니다.                     */
  if (!없는것.length) {
    console.log('      · 셋 다 살아 있으므로 <b>「아직 세는 자리가 없습니다」 는 안 뜹니다</b>');
    is(/function\s+hmSideTodoHtml\s*\(/.test(SRC),
       '  ⚠ 그래도 <b>hmSideTodoHtml 은 안 지웁니다</b> — 칸이 늘면 다시 쓰는 「한 곳」 입니다 (5번 · 함수를 지우지 마십시오)');
  }
}

console.log('\n[3] ⚠ <b>헛것을 안 잡나</b> — 「아직 못 읽었습니다」 는 다른 말입니다 (8번)');
/* 주석·판 쪽지를 걷어내고 <b>화면에 찍히는 글</b>만 셉니다 */
const 날글 = SRC.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/<!--[\s\S]*?-->/g, ' ')
                .replace(/^var APP_BUILD_NOTE=.*$/m, ' ');
const 못읽 = (날글.match(/아직 못 읽/g) || []).length;
is(못읽 > 0,
   '  「<b>아직 못 읽었습니다</b>」 ' + 못읽 + '곳은 <b>안 셉니다</b>' +
   ' — 서버에서 안 읽어 온 것이라 <b>참일 수 있습니다</b> (1번). 0곳이면 이 자가 잘못 지운 것입니다');
const 못셈 = (날글.match(/세는 자리가 없/g) || []).length;
console.log('      · 화면에 「세는 자리가 없」 이라 적는 자리 ' + 못셈 + '곳 — ' +
  (못셈 ? '<b>모양을 만드는 한 곳</b>입니다(hmSideTodoHtml). 떠야 하는지는 [2] 가 봅니다' : '없습니다'));

console.log('\n──────────────────────────────');
console.log(bad ? ('✗ ' + bad + '가지 빨간불')
  : '✓ 「못 한다」 고 적은 말이 아직 사실입니다 — 지도가 낡지 않았습니다.');
process.exit(bad ? 1 : 0);
