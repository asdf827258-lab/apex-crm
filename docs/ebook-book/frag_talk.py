def deck():
    out = []
    for no, nm, col, slides in DECK:
        items = "\n".join(f'''      <div class="tk-s">
        <div class="tk-sn">{sid}</div>
        <div class="tk-sb">
          <h4>{title}</h4>
          <p class="tk-do">{what}</p>
          <p class="tk-tip"><b>여기서 놓치기 쉬운 것</b> {tip}</p>
        </div>
      </div>''' for sid, title, what, tip in slides)
        out.append(f'''    <div class="tk-ch" style="--ch:{col}">
      <div class="tk-ch-h"><span class="tk-no">CHAPTER {no}</span><b>{nm}</b></div>
{items}
    </div>''')
    return "\n".join(out)


