W = "web"


def img(name, alt, pins):
    """사진 하나 + 번호 핀. pins = [(왼쪽%, 위%), ...]"""
    b = base64.b64encode(open(f"{W}/{name}.webp", "rb").read()).decode()
    dots = "".join(
        f'<span class="pin" style="left:{l}%;top:{t}%" aria-hidden="true">{i}</span>'
        for i, (l, t) in enumerate(pins, 1))
    return (f'<div class="pw-i"><img alt="{alt}" '
            f'src="data:image/webp;base64,{b}">{dots}</div>')


def fig(name, alt, cap, pins, steps, note=None, warn=None):
    out = [f'<figure class="pw">{img(name, alt, pins)}',
           f'<figcaption>{cap}</figcaption></figure>',
           '<div class="ms-do"><p class="ms-h">번호대로 보십시오</p><ol>']
    out += [f'<li>{s}</li>' for s in steps]
    out.append('</ol></div>')
    if note:
        out.append(f'<div class="ms-tip">{note}</div>')
    if warn:
        out.append(f'<div class="ms-warn">{warn}</div>')
    return "\n".join(out)


