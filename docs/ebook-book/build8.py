"""8차 — 책의 말을 화면의 말에 맞춘다.

  기준은 하나다. **화면에 찍힌 글자가 옳다.**
  책이 다르게 부르고 있으면 책을 고친다. 앱은 건드리지 않는다.
"""
import re, sys
sys.stdout.reconfigure(encoding="utf8")
S = open("book-final.html", encoding="utf8").read()
LOG = []


def subn(old, new, tag, n):
    global S
    c = S.count(old)
    assert c == n, f"[{tag}] {n}건 기대, 실제 {c}건 — {old[:70]!r}"
    S = S.replace(old, new)
    LOG.append(f"  ✓ {tag} ({n})")


