def sub1(old, new, n=1, tag=""):
    """정확히 n 번 나오는 문자열만 바꾼다."""
    global S
    c = S.count(old)
    assert c == n, f"[{tag}] 기대 {n}건, 실제 {c}건 — {old[:70]!r}"
    S = S.replace(old, new)
    LOG.append(f"  ✓ {tag} ({n})")


