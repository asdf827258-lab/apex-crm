def ex_rows():
    return "\n".join(
        f'      <tr><td class="s">{n}</td><td class="k">{v}/{t}</td>'
        f'<td><b>{s}점</b></td><td>{"기준 넘음" if s >= 100 else f"{100-s} 남음"}</td></tr>'
        for n, v, t, s in EX_S)


def up_rows():
    return "\n".join(
        f'''      <div class="lv-u"><div class="lv-ux"><b>{n} 을(를) 기준까지</b>'''
        f'''<span>지금 {v} → {t}</span></div>'''
        f'''<div class="lv-uv">+{jsr(g/6)}<em>점</em></div></div>'''
        for n, g, v, t in GAPS[:3])


