def jsr(x):
    """자바스크립트 Math.round — 0.5 는 늘 위로. 파이썬 round 와 다르다."""
    import math
    return math.floor(x + 0.5)


def pct(v, t):
    return max(0, min(100, jsr(v / t * 100)))


EX_S = [(n, v, t, pct(v, t)) for n, v, t in EX]
EX_TOT = jsr(sum(s for _, _, _, s in EX_S) / 6)
GAPS = sorted(((n, 100 - s, v, t) for n, v, t, s in EX_S), key=lambda x: -x[1])
ALL_UP = min(100, EX_TOT + jsr(sum(100 - s for _, _, _, s in EX_S) / 6))


